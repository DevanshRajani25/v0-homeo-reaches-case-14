// Normalize function
function norm(s: string) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
}

export function detectCategoryFromInput(input: string): CategoryKey | null {
  const text = norm(input)
  for (const entry of MASTER) {
    for (const term of entry.terms) {
      const t = norm(term)
      if (!t) continue
      if (text.includes(t)) return entry.key
    }
  }
  return null
}
